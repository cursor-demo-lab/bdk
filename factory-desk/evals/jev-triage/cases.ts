// The Jev triage eval set: marsbank requests as teammates type them in
// #mars-eng-intake, each labelled with the Jira type and severity a careful
// triager would file. `text` is the message after the @factory mention; the
// replay adds the mention. Labels follow the rubric in
// agent/lib/triage-rubric.ts and ISSUE_TYPE_CRITERIA in agent/lib/jev-triage.ts:
//
// - Bug: existing behaviour that is broken, missing, or wrong against what the
//   user expects, however softly it is put ("doesn't show", "used to",
//   "stopped working", "is wrong", "I typed X but"), even when the reporter
//   also suggests the fix.
// - Story: a new capability, or a change to behaviour that works as built.
// - Task: a chore (upgrade, rename, clean-up, config) or a question to answer.
//
// `accept` lists the other answers a careful triager could defend on a
// genuinely ambiguous case; accuracy counts them, strict accuracy does not.
// `clearBug` marks the set the "no bug filed as a Story" bar is measured on.
// `source` names a real run the text is copied from, verbatim. The frozen
// holdout set is holdout.ts (`holdout: true`): it is never tuned against,
// so its score shows whether the criteria generalise.

export type JiraType = "Bug" | "Story" | "Task";

export type Category = "bug" | "story" | "task" | "question" | "ambiguous" | "incident" | "form-input";

export type JevTriageCase = {
  id: string;
  text: string;
  type: JiraType;
  severity: TriageSeverity;
  accept?: { type?: readonly JiraType[]; severity?: readonly TriageSeverity[] };
  category: Category;
  clearBug?: true;
  /** In holdout.ts: frozen, never tuned against, the check on overfitting. */
  holdout?: true;
  source?: string;
  rationale: string;
};

